# Primitive Data Types:-5-str/int/float/bool/complex
# All primitive data types are immutable
empName="Sonali Ashish Maind"
print("Employee Name:",empName)
print("Type:",type(empName))

age=32
print("Employee Age:",age)
print("Type:",type(age))

marital_status=True
print("Marital Status:",marital_status)
print("Type:",type(marital_status)) # bool


per=89.70
print("Percentage:",per)
print("Type:",type(per))


x=20+10j # complex
print("Value:",x)
print("Type:",type(x))