#!/usr/bin/env python3
"""
build_site.py - compile topics/*.md into ONE self-contained study app (index.html)
and a QUESTION_INDEX.md. No dependencies. Works for ANY language/stack: just add
a new topics/<nn>-<slug>.md file following topics/_TEMPLATE.md.

Usage:  python3 build_site.py [--topics topics] [--out index.html]
"""
import argparse, glob, html, json, os, re, sys

Q_RE = re.compile(r"^###\s+Q(\d+)\s+\[(basic|intermediate|advanced|design)\]\s+(.*)$", re.I)
# Anything that looks like a question heading but does not match Q_RE is reported, never skipped.
LOOSE_Q_RE = re.compile(r"^#{2,4}\s*Q\s*\d+", re.I)
LEVELS = ("basic", "intermediate", "advanced", "design")
MIN_Q, MAX_Q, MIN_DESIGN = 15, 25, 3


def parse_topic(path):
    text = open(path, encoding="utf-8").read()
    meta, body = {}, text
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    if m:
        for line in m.group(1).splitlines():
            if ":" in line:
                k, v = line.split(":", 1)
                meta[k.strip()] = v.strip()
        body = m.group(2)
    questions, cur, in_code = [], None, False
    intro, problems = [], []
    for line in body.splitlines():
        if line.strip().startswith("```"):
            in_code = not in_code
        qm = None if in_code else Q_RE.match(line)
        if not in_code and not qm and LOOSE_Q_RE.match(line):
            problems.append(f"malformed question heading: {line.strip()[:70]!r}")
        if qm:
            cur = {"n": int(qm.group(1)), "level": qm.group(2).lower(),
                   "q": qm.group(3).strip(), "a": []}
            questions.append(cur)
        elif cur is not None:
            cur["a"].append(line)
        else:
            intro.append(line)
    for q in questions:
        q["a"] = "\n".join(q["a"]).strip()
    meta["id"] = meta.get("id") or os.path.splitext(os.path.basename(path))[0]
    meta["title"] = meta.get("title") or meta["id"]
    meta["intro"] = "\n".join(intro).strip()
    meta["questions"] = questions
    meta["problems"] = problems
    return meta


def write_index(topics, out):
    lines = ["# Question Index", "",
             "Auto-generated by `build_site.py`. Open `index.html` for the interactive version.", "",
             "| # | Topic | Questions | Basic | Intermediate | Advanced | Design |",
             "|---|-------|-----------|-------|--------------|----------|--------|"]
    tot = 0
    for i, t in enumerate(topics, 1):
        c = {l: sum(1 for q in t["questions"] if q["level"] == l)
             for l in ("basic", "intermediate", "advanced", "design")}
        n = len(t["questions"]); tot += n
        lines.append(f"| {i} | {t['title']} | {n} | {c['basic']} | {c['intermediate']} | {c['advanced']} | {c['design']} |")
    lines += ["", f"**Total: {tot} questions across {len(topics)} topics.**", ""]
    for t in topics:
        lines += [f"## {t['title']}", ""]
        for q in t["questions"]:
            lines.append(f"- Q{q['n']} `{q['level']}` {q['q']}")
        lines.append("")
    open(out, "w", encoding="utf-8").write("\n".join(lines))
    return tot


