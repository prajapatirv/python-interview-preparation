def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--topics", default="topics")
    ap.add_argument("--out", default="index.html")
    ap.add_argument("--title", default="Technical Interview Prep")
    a = ap.parse_args()
    files = sorted(f for f in glob.glob(os.path.join(a.topics, "*.md")) if not os.path.basename(f).startswith("_"))
    if not files:
        sys.exit("No topic files found in " + a.topics)
    topics = [parse_topic(f) for f in files]
    data = json.dumps([{k: v for k, v in t.items() if k != "problems"} for t in topics],
                      ensure_ascii=False).replace("</", "<\\/")
    open(a.out, "w", encoding="utf-8").write(PAGE.replace("__DATA__", data).replace("__TITLE__", html.escape(a.title)))
    tot = write_index(topics, os.path.join(os.path.dirname(os.path.abspath(a.out)), "QUESTION_INDEX.md"))
    print(f"Built {a.out}: {len(topics)} topics, {tot} questions")
    issues = 0
    for t in topics:
        n = len(t["questions"])
        nd = sum(1 for q in t["questions"] if q["level"] == "design")
        warns = list(t["problems"])
        if not MIN_Q <= n <= MAX_Q:
            warns.append(f"{n} questions, outside {MIN_Q}-{MAX_Q} target")
        if nd < MIN_DESIGN:
            warns.append(f"only {nd} design question(s), want >= {MIN_DESIGN}")
        issues += len(warns)
        print(f"  {t['id']:<28} {n:>3}  design={nd}")
        for w in warns:
            print(f"      WARN: {w}")
    print("Validation: OK" if not issues else f"Validation: {issues} warning(s)")
    if any(t["problems"] for t in topics):
        sys.exit(1)


if __name__ == "__main__":
    main()
